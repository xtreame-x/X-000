def get_templates():
    """List available tool templates."""
    lines = ["\033[90mavailable templates:\033[0m"]
    for name, tmpl in TOOL_TEMPLATES.items():
        lines.append(f"  \033[34m{name}\033[0m — {tmpl['description']}")
    return '\n'.join(lines)


def create_from_template(template_name, plugin_name, command=None):
    """Create a plugin from a pre-built template."""
    if template_name not in TOOL_TEMPLATES:
        return f"unknown template: {template_name}\nuse 'templates' to list available"

    tmpl = TOOL_TEMPLATES[template_name]
    cmd = command or plugin_name.replace('_', '-')

    return create_plugin(
        name=plugin_name,
        description=tmpl['description'],
        command=cmd,
        execute_body=tmpl['code'],
        help_text=tmpl['description'],
    )


