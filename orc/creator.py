def create_action(name, execute_body):
    """
    Create a new action that can be invoked via [ACT].
    
    Args:
        name: Action name (UPPER_CASE)
        execute_body: Python code for execute() function
    
    Returns:
        Status message
    """
    # Validate name
    if not re.match(r'^[A-Z][A-Z0-9_]*$', name):
        return f"error: action name must be UPPER_CASE (got: {name})"

    # Check if action exists
    action_path = os.path.join(ACTIONS_DIR, f"{name.lower()}.py")
    if os.path.exists(action_path):
        return f"error: action '{name}' already exists"

    # Ensure actions dir exists
    os.makedirs(ACTIONS_DIR, exist_ok=True)

    # Generate action code (indent body to match function level)
    indented_body = '\n'.join('    ' + line if line.strip() else '' for line in execute_body.splitlines())
    code = ACTION_TEMPLATE.format(
        name=name,
        execute_body=indented_body,
        date=datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
    )

    # Write action file
    with open(action_path, 'w') as f:
        f.write(code)

    return f"action created: {action_path}\nready for immediate use"


