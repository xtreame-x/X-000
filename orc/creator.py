def create_plugin(name, description, command, execute_body, help_text=None):
    """
    Create a new plugin from specification.
    
    Args:
        name: Plugin name (snake_case)
        description: What the plugin does
        command: Command name users will type
        execute_body: Python code for execute() method
        help_text: Help text for the command
    
    Returns:
        Status message
    """
    # Validate name
    if not re.match(r'^[a-z][a-z0-9_]*$', name):
        return f"error: plugin name must be snake_case (got: {name})"

    # Check if plugin exists
    plugin_path = os.path.join(PLUGINS_DIR, f"{name}.py")
    if os.path.exists(plugin_path):
        return f"error: plugin '{name}' already exists"

    # Generate class name
    class_name = ''.join(word.capitalize() for word in name.split('_')) + 'Plugin'
    if not help_text:
        help_text = f"{description}"

    # Ensure plugins dir exists
    os.makedirs(PLUGINS_DIR, exist_ok=True)

    # Generate plugin code (indent body to match method level)
    indented_body = '\n'.join('        ' + line if line.strip() else '' for line in execute_body.splitlines())
    code = PLUGIN_TEMPLATE.format(
        name=name,
        class_name=class_name,
        description=description,
        command=command,
        help_text=help_text,
        execute_body=indented_body,
        date=datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
    )

    # Write plugin file
    with open(plugin_path, 'w') as f:
        f.write(code)

    logger.info(f"Created plugin: {name} at {plugin_path}")

    # Immediately hot-reload into active loader if available
    try:
        from orc.plugins.loader import get_loader
        loader = get_loader()
        if loader:
            loader.reload_plugins()
            return f"plugin created and loaded: {name} (command: {command})"
    except Exception as e:
        logger.debug(f"Plugin reload notice: {e}")

    return f"plugin created: {plugin_path}\nready to use"


def create_plugin_from_spec(spec):
    """
    Create plugin from a natural language specification.
    
    Spec format:
        name: <plugin_name>
        description: <what it does>
        command: <command_name>
        help: <help text>
        code: <python code for execute body>
    """
    lines = spec.strip().split('\n')
    fields = {}
    current_field = None
    code_lines = []

    for line in lines:
        if ':' in line and not line.startswith(' '):
            parts = line.split(':', 1)
            field = parts[0].strip().lower()
            value = parts[1].strip()
            
            if field == 'code':
                current_field = 'code'
                code_lines.append(value)
            else:
                current_field = field
                fields[field] = value
        elif current_field == 'code':
            code_lines.append(line)

    if 'name' not in fields:
        return "error: missing 'name' field"
    if 'description' not in fields:
        return "error: missing 'description' field"
    if 'command' not in fields:
        return "error: missing 'command' field"

    execute_body = '\n        '.join(code_lines) if code_lines else 'pass'

    return create_plugin(
        name=fields['name'],
        description=fields['description'],
        command=fields['command'],
        execute_body=execute_body,
        help_text=fields.get('help', fields['description']),
    )


