def list_plugins():
    """List all user-created plugins."""
    if not os.path.isdir(PLUGINS_DIR):
        return "no plugins directory"

    plugins = []
    for f in os.listdir(PLUGINS_DIR):
        if f.endswith('.py') and not f.startswith('_'):
            plugins.append(f[:-3])

    if not plugins:
        return "no user plugins found"

    lines = ["\033[90muser plugins:\033[0m"]
    for p in sorted(plugins):
        lines.append(f"  \033[34m{p}\033[0m")
    return '\n'.join(lines)


def list_actions():
    """List all user-created actions."""
    if not os.path.isdir(ACTIONS_DIR):
        return "no actions directory"

    actions = []
    for f in os.listdir(ACTIONS_DIR):
        if f.endswith('.py') and not f.startswith('_'):
            actions.append(f[:-3].upper())

    if not actions:
        return "no user actions found"

    lines = ["\033[90muser actions:\033[0m"]
    for a in sorted(actions):
        lines.append(f"  \033[34m{a}\033[0m")
    return '\n'.join(lines)


def delete_plugin(name):
    """Delete a user-created plugin."""
    plugin_path = os.path.join(PLUGINS_DIR, f"{name}.py")
    if not os.path.exists(plugin_path):
        return f"plugin not found: {name}"

    os.remove(plugin_path)
    logger.info(f"Deleted plugin: {name}")
    return f"deleted plugin: {name}"


def delete_action(name):
    """Delete a user-created action."""
    action_path = os.path.join(ACTIONS_DIR, f"{name.lower()}.py")
    if not os.path.exists(action_path):
        return f"action not found: {name}"

    os.remove(action_path)
    logger.info(f"Deleted action: {name}")
    return f"deleted action: {name}"
