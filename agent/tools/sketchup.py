"""Trimble SketchUp tools (5), deferred behind ``tool_search``.

SketchUp cannot be driven without the desktop application, so these tools do the
thing that *is* deterministic and useful offline: they validate a declarative
model spec and emit a SketchUp Ruby script plus a JSON model record. Open the
``.rb`` file in SketchUp's Ruby console (or run it with ``sketchup -RubyStartup``)
to build the geometry.

Units are converted from the spec's unit to SketchUp's internal inches.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Literal

from agent.platform_compat import slugify
from agent.state import now_iso
from agent.tools.base import ToolContext, ToolResult, tool

MODELS = "sketchup/models.json"
USAGE = "sketchup/usage.json"
MAX_COMPONENTS = 100

UNIT_TO_INCHES = {"mm": 1 / 25.4, "cm": 1 / 2.54, "m": 39.3701, "in": 1.0, "ft": 12.0}
SHAPES = {"box", "cylinder", "prism"}

SKILLS: dict[str, str] = {
    "build_model": (
        "# build_model\n\n"
        "Describe the model as components:\n"
        '{"type": "box", "size": [2000, 1200, 300], "position": [0, 0, 0], "name": "Slab"}\n\n'
        "Every component becomes a group so parts stay editable separately. "
        "Positions are the component's minimum corner (box), base centre (cylinder) "
        "or base centre (prism). Units default to millimetres."
    ),
    "components": (
        "# components\n\n"
        "- box: axis-aligned box, size = width x depth x height.\n"
        "- cylinder: size = diameter x diameter x height.\n"
        "- prism: size = width x depth x height, triangular cross-section.\n\n"
        "Groups are named after the component so the outliner stays readable."
    ),
    "materials": (
        "# materials\n\n"
        "Add \"material\": {\"name\": \"Concrete\", \"color\": \"#cccccc\"} to a component. "
        "The generated script creates the material if it does not exist and applies it "
        "to the group's faces."
    ),
    "ruby_api": (
        "# SketchUp Ruby API\n\n"
        "The generated script uses Sketchup.active_model, entities.add_group, "
        "add_face and face.pushpull. Operations are wrapped in start_operation / "
        "commit_operation so a failure leaves the model untouched."
    ),
}


def _vec3(value: Any, field: str, *, positive: bool = False) -> list[float]:
    if not isinstance(value, (list, tuple)) or len(value) != 3:
        raise ValueError(f"{field} must be an array of 3 numbers, got {value!r}")
    try:
        numbers = [float(v) for v in value]
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field} must contain numbers, got {value!r}") from exc
    if positive and any(number <= 0 for number in numbers):
        raise ValueError(f"{field} must be positive, got {value!r}")
    return numbers


def validate_spec(components: list[dict]) -> list[dict]:
    if not components:
        raise ValueError("components must be a non-empty array")
    if len(components) > MAX_COMPONENTS:
        raise ValueError(f"components is capped at {MAX_COMPONENTS}, got {len(components)}")
    validated = []
    for index, item in enumerate(components, 1):
        if not isinstance(item, dict):
            raise ValueError(f"component #{index} must be an object")
        shape = str(item.get("type", "")).strip()
        if shape not in SHAPES:
            raise ValueError(
                f"component #{index}: unsupported type {shape!r}; use one of {sorted(SHAPES)}"
            )
        material = item.get("material") or {}
        if material and not isinstance(material, dict):
            raise ValueError(f"component #{index}: material must be an object")
        validated.append(
            {
                "type": shape,
                "name": str(item.get("name") or f"{shape.title()} {index}"),
                "size": _vec3(item.get("size", [1000, 1000, 1000]), f"component #{index}.size",
                              positive=True),
                "position": _vec3(item.get("position", [0, 0, 0]), f"component #{index}.position"),
                "material": {
                    "name": str(material.get("name", "Default")),
                    "color": str(material.get("color", "#cbd5e1")),
                }
                if material
                else None,
            }
        )
    return validated


def _ruby(model_id: str, title: str, components: list[dict], units: str) -> str:
    scale = UNIT_TO_INCHES[units]
    lines = [
        "# Generated by OpenAgent — SketchUp Ruby script",
        f"# Model: {title} ({model_id}), units: {units}",
        "def openagent_mm(value, scale) value.to_f * scale end",
        "",
        "model = Sketchup.active_model",
        f"model.start_operation('OpenAgent {model_id}', true)",
        "begin",
    ]
    for component in components:
        width, depth, height = component["size"]
        x, y, z = component["position"]
        lines.append("  group = model.active_entities.add_group")
        lines.append(f"  group.name = {json.dumps(component['name'])}")
        if component["type"] == "box":
            points = [
                (x, y, z), (x + width, y, z), (x + width, y + depth, z), (x, y + depth, z),
            ]
            lines.append(
                "  face = group.entities.add_face(["
                + ", ".join(
                    f"[openagent_mm({px}, {scale}), openagent_mm({py}, {scale}), openagent_mm({pz}, {scale})]"
                    for px, py, pz in points
                )
                + "])"
            )
            lines.append(
                f"  face.pushpull(openagent_mm({height}, {scale}))"
            )
        elif component["type"] == "cylinder":
            radius = width / 2
            lines.append(
                f"  circle = group.entities.add_circle("
                f"[openagent_mm({x}, {scale}), openagent_mm({y}, {scale}), openagent_mm({z}, {scale})], "
                f"openagent_mm({radius}, {scale}), 48)"
            )
            lines.append(
                "  face = group.entities.add_face(circle)"
            )
            lines.append(f"  face.pushpull(openagent_mm({height}, {scale}))")
        else:  # prism
            points = [(x, y, z), (x + width, y, z), (x + width / 2, y + depth, z)]
            lines.append(
                "  face = group.entities.add_face(["
                + ", ".join(
                    f"[openagent_mm({px}, {scale}), openagent_mm({py}, {scale}), openagent_mm({pz}, {scale})]"
                    for px, py, pz in points
                )
                + "])"
            )
            lines.append(f"  face.pushpull(openagent_mm({height}, {scale}))")
        material = component.get("material")
        if material:
            lines.append(
                f"  mat = model.materials[{json.dumps(material['name'])}] || "
                f"model.materials.add({json.dumps(material['name'])})"
            )
            lines.append(f"  mat.color = {json.dumps(material['color'])}")
            lines.append("  group.material = mat")
    lines += [
        "  model.commit_operation",
        "rescue => error",
        "  model.abort_operation",
        "  puts \"OpenAgent build failed: #{error.message}\"",
        "  raise",
        "end",
        "",
    ]
    return "\n".join(lines)


def _usage(ctx: ToolContext) -> dict:
    month = datetime.now(timezone.utc).strftime("%Y-%m")
    usage = ctx.state.read_json(USAGE, default={}) or {}
    record = usage.get(month, {"used": 0})
    limit = int(ctx.settings.secret("AGENT_SKETCHUP_MONTHLY_LIMIT") or 50)
    return {"month": month, "used": int(record.get("used", 0)), "limit": limit, "all": usage}


@tool(group="Trimble SketchUp", name="mcp__Trimble_SketchUp__list_skills",
      requires_tool_search=True, tags=("sketchup", "skills", "help", "docs"))
def mcp__Trimble_SketchUp__list_skills() -> ToolResult:
    """List the modelling skills and conventions supported by build_model."""
    body = "\n".join(f"- {name}: {text.splitlines()[2] if len(text.splitlines()) > 2 else ''}"
                     for name, text in SKILLS.items())
    return ToolResult.text(body, skills=sorted(SKILLS))


@tool(group="Trimble SketchUp", name="mcp__Trimble_SketchUp__read_skill",
      requires_tool_search=True, tags=("sketchup", "skill", "read", "docs"))
def mcp__Trimble_SketchUp__read_skill(skill: str) -> ToolResult:
    """Read one SketchUp modelling skill.

    Args:
        skill: Skill name from list_skills.
    """
    key = skill.strip().lower()
    if key not in SKILLS:
        return ToolResult.error(
            f"unknown skill {skill!r}", error="not_found", skills=sorted(SKILLS)
        )
    return ToolResult.text(SKILLS[key], skill=key)


@tool(group="Trimble SketchUp", name="mcp__Trimble_SketchUp__build_model",
      requires_tool_search=True, tags=("sketchup", "model", "build", "3d", "ruby"))
def mcp__Trimble_SketchUp__build_model(
    ctx: ToolContext,
    title: str,
    components: list[dict],
    units: Literal["mm", "cm", "m", "in", "ft"] = "mm",
) -> ToolResult:
    """Build a SketchUp model spec and generate the Ruby script that creates it.

    Args:
        title: Model name.
        components: Parts to create, each with type, size, position and optional material.
        units: Unit of the supplied dimensions.
    """
    usage = _usage(ctx)
    if usage["used"] >= usage["limit"]:
        return ToolResult.error(
            f"SketchUp monthly build limit reached ({usage['used']}/{usage['limit']} in {usage['month']})",
            error="usage_limit_reached",
            used=usage["used"],
            limit=usage["limit"],
            month=usage["month"],
        )
    try:
        validated = validate_spec(components)
    except ValueError as exc:
        return ToolResult.error(str(exc), error="invalid_spec")

    model_id = f"skp_{slugify(title, max_length=24)}_{len(_load_models(ctx)) + 1:03d}"
    script = _ruby(model_id, title, validated, units)
    record = {
        "id": model_id,
        "title": title,
        "units": units,
        "components": validated,
        "createdAt": now_iso(),
        "rubyScript": script,
    }
    models = _load_models(ctx)
    models.append(record)
    ctx.state.save_collection(MODELS, models)

    usage["all"][usage["month"]] = {"used": usage["used"] + 1}
    ctx.state.write_json(USAGE, usage["all"])

    path = ctx.save_artifact(script, name=f"{slugify(title)}-model", ext="rb", mime="text/plain")
    return ToolResult.text(
        f"built {model_id} with {len(validated)} component(s); Ruby script at {path['path']}",
        modelId=model_id,
        components=len(validated),
        units=units,
        rubyPath=path["path"],
        usage={"used": usage["used"] + 1, "limit": usage["limit"]},
    )


def _load_models(ctx: ToolContext) -> list[dict]:
    return ctx.state.collection(MODELS)


@tool(group="Trimble SketchUp", name="mcp__Trimble_SketchUp__save_model",
      requires_tool_search=True, tags=("sketchup", "save", "export", "model"))
def mcp__Trimble_SketchUp__save_model(
    ctx: ToolContext,
    model_id: str,
    filename: str | None = None,
) -> ToolResult:
    """Save a built model as a Ruby script plus a JSON record.

    Args:
        model_id: Identifier returned by build_model.
        filename: Optional file stem; defaults to the model title.
    """
    models = _load_models(ctx)
    record = next((item for item in models if item["id"] == model_id), None)
    if record is None:
        return ToolResult.error(f"no model {model_id!r}", error="not_found", modelId=model_id)

    stem = slugify(filename or record["title"])
    ruby_info = ctx.save_artifact(
        record["rubyScript"], name=f"{stem}-model", ext="rb", mime="text/plain"
    )
    record_copy = {key: value for key, value in record.items() if key != "rubyScript"}
    json_info = ctx.save_artifact(
        json.dumps(record_copy, indent=2) + "\n",
        name=f"{stem}-model",
        ext="json",
        mime="application/json",
    )
    return ToolResult.text(
        f"saved {model_id} to {ruby_info['path']} and {json_info['path']}",
        modelId=model_id,
        rubyPath=ruby_info["path"],
        jsonPath=json_info["path"],
        components=len(record["components"]),
    )


@tool(group="Trimble SketchUp", name="mcp__Trimble_SketchUp__usage_limit_reached",
      requires_tool_search=True, tags=("sketchup", "limit", "usage", "quota"))
def mcp__Trimble_SketchUp__usage_limit_reached(ctx: ToolContext) -> ToolResult:
    """Report whether the SketchUp build quota for this month is exhausted."""
    usage = _usage(ctx)
    reached = usage["used"] >= usage["limit"]
    return ToolResult.text(
        f"{'limit reached' if reached else 'within limit'}: "
        f"{usage['used']}/{usage['limit']} builds used in {usage['month']}",
        reached=reached,
        used=usage["used"],
        limit=usage["limit"],
        remaining=max(usage["limit"] - usage["used"], 0),
        month=usage["month"],
    )


